/** Country (ISO-3166-1 alpha-2) → default UI locale.
 *
 * Mapping is conservative: we only claim a non-English locale when the
 * country's official or dominant language matches one of our supported
 * translations. All other countries fall back to English.
 */
const COUNTRY_TO_LOCALE: Readonly<Record<string, Locale>> = {
  IR: "fa",
  AF: "fa", // Dari is mutually intelligible with Farsi
  TJ: "fa", // Tajik Persian
  TR: "tr",
  SA: "ar",
  AE: "ar",
  EG: "ar",
  IQ: "ar",
  JO: "ar",
  KW: "ar",
  LB: "ar",
  LY: "ar",
  MA: "ar",
  OM: "ar",
  QA: "ar",
  SD: "ar",
  SY: "ar",
  TN: "ar",
  YE: "ar",
  PS: "ar",
  DZ: "ar",
  BH: "ar",
  MR: "ar",
  SO: "ar",
  DJ: "ar",
};

/** Pick the best-fit locale for a given ISO country code.
 *  Unknown / missing codes default to English. */
export function localeFromCountry(code: string | null | undefined): Locale {
  if (!code) return "en";
  return COUNTRY_TO_LOCALE[code.toUpperCase()] ?? "en";
}

